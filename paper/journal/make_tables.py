PENDING = {"zerofill_flipout", "flipout"}


def uq_table():
	with open(os.path.join(R, "uq_grid_report.json")) as f:
		rep = json.load(f)
	lines = []
	for label, config in UQ_ROWS:
		if(config is None):
			lines.append("\\midrule\n\\multicolumn{11}{l}{\\emph{%s}}\\\\" % label)
			continue
		if(config in PENDING and not os.path.isdir(os.path.join(R, "summaries", config, "fold4"))):
			lines.append("%s & \\multicolumn{10}{c}{\\TBD{running (Slurm 208077)}}\\\\" % label)
			continue
		m = {k: config_mean(config, k)[0] for k in ["rmse_brain", "nll", "crps", "spearman", "ause"]}
		rmse_sd = config_mean(config, "rmse_brain")[1]
		picp = config_mean(config, "picp", I90)[0]
		conf = config_mean(config, "conf_voxel_cov", I90)[0]
		r = rep.get(config)
		p_nll = r["vs_template"]["nll"]["p"] if r and r["vs_template"]["nll"].get("p") is not None else None
		p_shift = r["temporal_r_vs_shift"]["p"] if r else None
		p_swap = r["temporal_r_vs_swap"]["p"] if r else None
		rmse = fmt(m["rmse_brain"]) + ("$_{\\pm %s}$" % fmt(rmse_sd) if rmse_sd is not None else "")
		lines.append(" & ".join([label, rmse, fmt(m["nll"]), fmt(m["crps"]), fmt(picp, 2), fmt(conf, 2),
			fmt(m["spearman"], 2), fmt(m["ause"]), pfmt(p_nll), pfmt(p_shift), pfmt(p_swap)])+"\\\\")
	write("uq_benchmark.tex", "\n".join(lines)+"\n")


