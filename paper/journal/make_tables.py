"""
Generates the LaTeX tables and macros of the journal draft from the saved run summaries (no recomputation).

Inputs (copied from Frida runs/ into results/):
	results/summaries/<config>/fold*/seed*/summary.json   per fold x seed, mean over the fold's test subjects
	results/uq_grid_report.json, gate1_report.json, gate2_*_report.json   paired subject-level tests (gate_report.py)
	results/oracle_05.json   oracle low-pass bound (oracle_bound.py)
	results/ridge*/ *.json   ROI ridge arm (ridge_roi.py)

python make_tables.py   -> tables/*.tex
"""
import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
T = os.path.join(HERE, "tables")
I90 = 8	#LEVELS[8] == 0.9 in evaluate_uq.py


def config_mean(config, key, index=None):
	"""Subject-weighted mean over folds of the seed-averaged fold means, and the SD across seeds of the overall mean."""
	folds = sorted(glob.glob(os.path.join(R, "summaries", config, "fold*")))
	if(not folds):
		return None, None, 0
	per_seed, weights, fold_means = {}, [], []
	for fold in folds:
		vals = {}
		for path in glob.glob(os.path.join(fold, "seed*", "summary.json")):
			with open(path) as f:
				s = json.load(f)
			v = s.get(key)
			if(v is None):
				continue
			v = v[index] if index is not None else v
			vals[os.path.basename(os.path.dirname(path))] = np.nan if v is None else float(v)
			n = len(s["subjects"])
		if(not vals):
			continue
		weights.append(n); fold_means.append(np.nanmean(list(vals.values())))
		for seed, v in vals.items():
			per_seed.setdefault(seed, []).append((n, v))
	w = np.array(weights, float)
	mean = float(np.sum(w*np.array(fold_means))/np.sum(w)) if len(w) else None
	full = [np.sum([a*b for a, b in x])/np.sum([a for a, _ in x]) for x in per_seed.values() if len(x) == len(folds)]
	sd = float(np.std(full, ddof=1)) if len(full) > 1 else None
	return mean, sd, len(folds)


def fmt(v, d=3):
	return "--" if v is None or not np.isfinite(v) else ("%."+str(d)+"f") % v


def pfmt(p):
	if(p is None):
		return "--"
	if(p < 0.001):
		return "$<$0.001"
	return ("\\textbf{%.3f}" if p < 0.05 else "%.3f") % p


def write(name, text):
	os.makedirs(T, exist_ok=True)
	with open(os.path.join(T, name), "w") as f:
		f.write("%auto-generated by make_tables.py; do not edit\n"+text)


