#----------------------------------------------------------------------------------------------- positive control (review #2)
def positive_control_table():
	"""Injected C3/C4 mu-power signal: closed-form ridge (linear_probe.py), the ablation ladder (ablation_ladder.py) and
	the full backbone (train_cv.py inject runs), median voxel r inside the injected box, mean over 17 test subjects."""
	def probe(name, cond, reg):
		v = {}
		for f in glob.glob(os.path.join(R, "probe", name, "fold*", "probe.json")):
			v.update(json.load(open(f))[cond].get(reg, {}))
		return np.mean(list(v.values())) if v else None
	def ladder(variant, snr, cond):
		v = {}
		for f in glob.glob(os.path.join(R, "ladder", "ladder_inject%s_%s" % (snr, variant), "fold*", "ladder.json")):
			v.update(json.load(open(f))[cond]["box"])
		return np.mean(list(v.values())) if v else None
	def network(snr, tag):
		v = [json.load(open(f))["temporal_r_inject"] for f in glob.glob(os.path.join(R, "summaries", "inject%s_hetero_fluct" % snr, "fold*", "seed2", "summary%s.json" % tag))]
		return np.mean(v) if len(v) == 5 else None
	cell = lambda a, b, c: "--" if a is None else "%s (%s, %s)" % (fmt(a), fmt(b), fmt(c))
	lines = []
	for snr in ["0.1", "0.3", "1"]:
		s_ = float(snr)
		row = ["%g" % s_, fmt(np.sqrt(s_/(1+s_))),
			cell(probe("probe_inject"+snr, "real", "box"), probe("probe_inject"+snr, "shift", "box"), probe("probe_inject"+snr, "swap", "box"))]
		for variant in ["linear_laplace", "linear_mse", "mlp_laplace", "mlp_mse"]:
			row.append(cell(ladder(variant, snr, "real"), ladder(variant, snr, "shift"), ladder(variant, snr, "swap")))
		row.append(cell(network(snr, ""), network(snr, "_null_shift"), network(snr, "_null_swap")))
		for cfg in ["inject%s_point_fluct", "inject%s_hetero_lr1e-4_b32_fluct"]:
			c = cfg % snr
			v = {t: [json.load(open(f))["temporal_r_inject"] for f in glob.glob(os.path.join(R, "summaries", c, "fold*", "seed2", "summary%s.json" % t))] for t in ["", "_null_shift", "_null_swap"]}
			row.append(cell(*[np.mean(v[t]) if len(v[t]) == 5 else None for t in ["", "_null_shift", "_null_swap"]]))
		lines.append(" & ".join(row)+"\\\\")
	write("positive_control.tex", "\n".join(lines)+"\n")


